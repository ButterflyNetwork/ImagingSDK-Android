import java.util.Properties

plugins {
    `kotlin-dsl`
    `java-gradle-plugin`
    alias(libs.plugins.vanniktech.publish)
}

val sdkProperties = Properties().apply {
    file("butterfly-imaging-sdk.properties")
        .inputStream()
        .use { load(it) }
}

fun sdkProperty(key: String): String =
    sdkProperties.getProperty(key)
        ?: error("Missing '$key' in butterfly-imaging-sdk.properties")

val sdkVersion = sdkProperty("version")
val sdkChecksum = sdkProperty("checksum")
val sdkUrl = sdkProperty("url")

group = "com.butterflynetwork.sdk"
version = sdkVersion

val generatedSdkInfo by tasks.registering {
    val outDir = layout.buildDirectory.dir("generated/sources/sdkInfo/kotlin/main")
    inputs.property("version", sdkVersion)
    inputs.property("checksum", sdkChecksum)
    inputs.property("url", sdkUrl)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().asFile.resolve("com/butterflynetwork/sdk/imaging")
        pkgDir.mkdirs()
        pkgDir.resolve("SdkInfo.kt").writeText(
            """
            // Generated by build.gradle.kts. Do not edit.
            package com.butterflynetwork.sdk.imaging

            internal object SdkInfo {
                const val VERSION = "$sdkVersion"
                const val CHECKSUM = "$sdkChecksum"
                const val URL = "$sdkUrl"
            }
            """.trimIndent() + "\n"
        )
    }
}

sourceSets.named("main") {
    java.srcDir(generatedSdkInfo)
}

gradlePlugin {
    plugins {
        create("butterflyImagingSDKLoaderPlugin") {
            id = "com.butterflynetwork.sdk.plugin.loader"
            implementationClass = "com.butterflynetwork.sdk.imaging.ButterflyImagingSDKLoaderPlugin"
        }
    }
}
